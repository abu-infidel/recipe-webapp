$created = [];

foreach ($articles as $entry) {
    $fieldId = $fieldIds[$entry['field']];
    $slug = Slug::make($entry['title']);

    // Give every heading a stable id and build the contents tree, exactly as
    // the publish pipeline does.
    $built = Toc::build($entry['body']);

    $articleId = Database::insert('articles', [
        'field_id'        => $fieldId,
        'slug'            => $slug,
        'kind'            => $entry['kind'],
        'status'          => 'published',
        'title_fa'        => $entry['title'],
        'summary_fa'      => $entry['summary'],
        'body_html'       => $built['html'],
        'toc_json'        => json_encode($built['toc'], JSON_UNESCAPED_UNICODE),
        'recipe_json'     => isset($entry['recipe'])
            ? json_encode($entry['recipe'], JSON_UNESCAPED_UNICODE)
            : null,
        'reading_minutes' => PersianText::readingMinutes($entry['body']),
        'ai_model'        => 'seed',
        'published_at'    => date('Y-m-d H:i:s', time() - random_int(0, 86400 * 45)),
    ]);

    $created[$entry['title']] = $articleId;

    // Numbered bibliography, in the order the markers appear in the text.
    foreach (array_values($entry['sources']) as $i => $sourceIndex) {
        Database::insert('article_sources', [
            'article_id' => $articleId,
            'source_id'  => $sourceIds[$sourceIndex],
            'marker'     => $i + 1,
        ]);
    }

    // The title is always an alias of itself, so other articles mentioning it
    // get an automatic internal link.
    Database::insert('topic_aliases', [
        'article_id' => $articleId,
        'alias'      => $entry['title'],
        'alias_norm' => PersianText::normalize($entry['title']),
        'priority'   => 10,
        'is_auto'    => 1,
    ]);

    SearchIndex::index($articleId, [
        SearchIndex::ZONE_TITLE   => $entry['title'],
        SearchIndex::ZONE_SUMMARY => $entry['summary'],
        SearchIndex::ZONE_BODY    => $entry['body'],
    ]);

    printf("  %s\n", $entry['title']);
}

